"""
scripts/create_sample_images.py
================================
Generate synthetic sample JPEG images for the two fixture samples.

Run once before starting the application:
    python scripts/create_sample_images.py

Creates:
    data/samples/sample_a.jpg  — dark background with warning-colour text overlay
    data/samples/sample_b.jpg  — light background with info-colour text overlay

These are purely synthetic test fixtures — not evaluation data.
"""
from __future__ import annotations

import pathlib
import sys

try:
    from PIL import Image, ImageDraw, ImageFont
except ImportError:
    print("ERROR: Pillow is required. Install it with: pip install Pillow")
    sys.exit(1)

SAMPLES_DIR = pathlib.Path(__file__).resolve().parent.parent / "data" / "samples"
SAMPLES_DIR.mkdir(parents=True, exist_ok=True)

WIDTH, HEIGHT = 512, 384


def _make_image(
    bg_color: tuple[int, int, int],
    text_color: tuple[int, int, int],
    lines: list[str],
    path: pathlib.Path,
) -> None:
    img = Image.new("RGB", (WIDTH, HEIGHT), color=bg_color)
    draw = ImageDraw.Draw(img)

    # Use default font (no external font files needed)
    try:
        font = ImageFont.truetype("arial.ttf", size=20)
        small_font = ImageFont.truetype("arial.ttf", size=14)
    except (IOError, OSError):
        font = ImageFont.load_default()
        small_font = font

    y = 30
    for i, line in enumerate(lines):
        f = font if i == 0 else small_font
        draw.text((20, y), line, fill=text_color, font=f)
        y += 35 if i == 0 else 22

    # Add a simple geometric shape to give the image visual structure
    draw.rectangle([WIDTH // 4, HEIGHT // 2, 3 * WIDTH // 4, 3 * HEIGHT // 4],
                   outline=text_color, width=3)
    draw.ellipse([WIDTH // 3, HEIGHT // 6, 2 * WIDTH // 3, HEIGHT // 3],
                 outline=text_color, width=2)

    img.save(path, format="JPEG", quality=90)
    print(f"Created: {path}")


def main() -> None:
    _make_image(
        bg_color=(30, 30, 50),
        text_color=(255, 160, 60),
        lines=[
            "Sample A — Synthetic Fixture",
            "SYNTHETIC TEST IMAGE — NOT REAL CONTENT",
            "Caption: Protesters at parliament",
            "Expected: Mismatch code path",
            "This file was generated by create_sample_images.py",
        ],
        path=SAMPLES_DIR / "sample_a.jpg",
    )

    _make_image(
        bg_color=(240, 248, 255),
        text_color=(20, 80, 160),
        lines=[
            "Sample B — Synthetic Fixture",
            "SYNTHETIC TEST IMAGE — NOT REAL CONTENT",
            "Caption: Stadium crowd at championship",
            "Expected: Match code path",
            "This file was generated by create_sample_images.py",
        ],
        path=SAMPLES_DIR / "sample_b.jpg",
    )

    print("Done. Sample images created in data/samples/")


if __name__ == "__main__":
    main()
